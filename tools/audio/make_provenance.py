"""Write data/audio/PROVENANCE.toml: one [[file]] entry per .wav / .ogg under data/audio and data/music (M13-47).

Rules (first match wins; paths are relative to data/):
  music/**                                   -> ace-step-1.5      (tools/audio/export_music.py)
  audio/voice/**                             -> kokoro-82m        (tools/voice/kokoro_batch.py)
  audio/sfx/<id>.wav, <id> is a job in       -> stable-audio-open-1.0 (tools/audio/sfx/make_sfx.py)
    tools/audio/sfx/sfx_jobs.toml
  audio/sfx/<id>.wav, <id> is a [sound.<id>] -> sfxr              (tools/audio/sfxr.py)
    in tools/audio/presets.toml
  anything else                              -> unknown, licence "unknown — ask owner"

Licence wording is copied from the Audio table in docs/CREDITS.md. Nothing is guessed: a file that matches no rule
is written as "unknown" and the checker (tools/audio/check_provenance.py) reports it.

Usage:  python3 tools/audio/make_provenance.py
"""

import json
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DATA = ROOT / "data"
OUT = DATA / "audio" / "PROVENANCE.toml"
JOBS = ROOT / "tools" / "audio" / "sfx" / "sfx_jobs.toml"
PRESETS = ROOT / "tools" / "audio" / "presets.toml"

UNKNOWN = "unknown"
UNKNOWN_LICENCE = "unknown — ask owner"

# Licence wording per source, as in docs/CREDITS.md. The checker imports these, so there is one source of truth.
LICENCE = {
    "sfxr": "CC0 (ASSUMED, owner to confirm)",
    "stable-audio-open-1.0": "Stability AI Community License; shipped under GPL-3.0",
    "ace-step-1.5": "CC0",
    "kokoro-82m": "Apache-2.0 model; output CC0 (ASSUMED)",
}

# The repo script that makes each source's files.
TOOL = {
    "sfxr": "tools/audio/sfxr.py",
    "stable-audio-open-1.0": "tools/audio/sfx/make_sfx.py",
    "ace-step-1.5": "tools/audio/export_music.py",
    "kokoro-82m": "tools/voice/kokoro_batch.py",
}


def audio_files() -> list[str]:
    """Every .wav / .ogg under data/audio and data/music, as paths relative to data/, sorted."""
    found = []
    for top in ("audio", "music"):
        for path in (DATA / top).rglob("*"):
            if path.is_file() and path.suffix in (".wav", ".ogg"):
                found.append(path.relative_to(DATA).as_posix())
    return sorted(found)


def classify(rel: str, jobs: set[str], presets: set[str]) -> tuple[str, str]:
    """Return (source, notes) for a path relative to data/, by the rules in the module docstring."""
    parts = rel.split("/")
    stem = Path(rel).stem
    if parts[0] == "music":
        return "ace-step-1.5", "ACE-Step 1.5 take exported by tools/audio/export_music.py"
    if parts[:2] == ["audio", "voice"]:
        return "kokoro-82m", "preset voice per leader in tools/voice/leaders.json"
    if parts[:2] == ["audio", "sfx"]:
        if stem in jobs:
            return "stable-audio-open-1.0", f"prompt in tools/audio/sfx/sfx_jobs.toml [job.{stem}]"
        if stem in presets:
            return "sfxr", f"preset [sound.{stem}] in tools/audio/presets.toml"
    return UNKNOWN, "no generator rule matches this file; owner to confirm its source"


def toml_str(value: str) -> str:
    """A TOML basic string. JSON escaping is valid TOML for the text used here."""
    return json.dumps(value, ensure_ascii=False)


def entry(rel: str, source: str, notes: str) -> str:
    """One [[file]] table."""
    lines = ["[[file]]", f"path = {toml_str(rel)}", f"source = {toml_str(source)}"]
    if source != UNKNOWN:
        lines.append(f"tool = {toml_str(TOOL[source])}")
        lines.append(f"licence = {toml_str(LICENCE[source])}")
    else:
        lines.append(f"licence = {toml_str(UNKNOWN_LICENCE)}")
    lines.append(f"notes = {toml_str(notes)}")
    return "\n".join(lines) + "\n"


def main() -> int:
    jobs = set(tomllib.loads(JOBS.read_text(encoding="utf-8"))["job"].keys())
    presets = set(tomllib.loads(PRESETS.read_text(encoding="utf-8"))["sound"].keys())

    header = (
        "# Per-file provenance of every shipped sound and music file (M13-47).\n"
        "# GENERATED by tools/audio/make_provenance.py: do not edit by hand, re-run the script.\n"
        "# Checked by tools/audio/check_provenance.py and tests/Game.Tests/Audio/AudioProvenanceTests.cs.\n"
        "# Licence wording comes from docs/CREDITS.md (Audio table). Paths are relative to data/.\n"
    )
    blocks = []
    counts: dict[str, int] = {}
    for rel in audio_files():
        source, notes = classify(rel, jobs, presets)
        counts[source] = counts.get(source, 0) + 1
        blocks.append(entry(rel, source, notes))

    OUT.write_text(header + "\n" + "\n".join(blocks), encoding="utf-8", newline="\n")
    summary = ", ".join(f"{k} {counts[k]}" for k in sorted(counts))
    print(f"wrote {OUT.relative_to(ROOT).as_posix()}: {sum(counts.values())} files ({summary})")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
