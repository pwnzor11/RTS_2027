"""Cuts prop sprites out of the Liberated Pixel Cup terrain atlas into data/sprites/props/lpc_props.png + lpc_props.props.toml (S15 pilot).

Usage:  python3 tools/art/fx/import_lpc_props.py [--atlas PATH]    # default: $RTS_ART_PACKS/Atlas/terrain_atlas.png or /tmp/claude-0/s15-packs/Atlas/terrain_atlas.png
Source: LPC terrain_atlas.png (CC-BY-SA 3.0 / GPL-3.0 dual; used under GPL-3.0). Artists: see docs/CREDITS.md (the whole LPC Attribution.txt list).
Pieces are lifted at 1x (native 32 px LPC scale, no resampling): each is the connected blob around a seed pixel (pieces closer than GAP px merge),
or a hand-picked box, or a small composite. Only top-down-friendly pieces are used (rocks, stumps, bricks, craters, concrete chunks); cliff walls and
anything front-facing are left out. The PNG keeps the atlas colours; the game recolours lightly toward each theater's land ramp at load.
Frames map onto the existing PropKind values (variant 0 small .. 2 large); kinds without LPC art keep the procedural placeholder.
"""
import argparse, os
import numpy as np
from PIL import Image

HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.abspath(os.path.join(HERE, "..", "..", ".."))
OUT = os.path.join(ROOT, "data", "sprites", "props")
GAP = 2


def blob(a, seed, gap=GAP):
    """The pixels connected to `seed` (x, y), treating pieces within `gap` px as connected. Returns a cropped RGBA array."""
    h, w = a.shape[:2]
    solid = a[..., 3] > 0
    seen = np.zeros((h, w), dtype=bool)
    sx, sy = seed
    if not solid[sy, sx]:                                   # nudge to the nearest solid pixel
        ys, xs = np.where(solid[max(0, sy - 6):sy + 7, max(0, sx - 6):sx + 7])
        k = np.argmin((ys - 6) ** 2 + (xs - 6) ** 2)
        sy, sx = max(0, sy - 6) + ys[k], max(0, sx - 6) + xs[k]
    stack = [(sx, sy)]
    seen[sy, sx] = True
    while stack:
        x, y = stack.pop()
        for yy in range(max(0, y - gap), min(h, y + gap + 1)):
            for xx in range(max(0, x - gap), min(w, x + gap + 1)):
                if solid[yy, xx] and not seen[yy, xx]:
                    seen[yy, xx] = True
                    stack.append((xx, yy))
    ys, xs = np.where(seen)
    x0, x1, y0, y1 = xs.min(), xs.max() + 1, ys.min(), ys.max() + 1
    out = np.zeros((y1 - y0, x1 - x0, 4), dtype=np.uint8)
    m = seen[y0:y1, x0:x1]
    out[m] = a[y0:y1, x0:x1][m]
    return out


def box(a, b):
    l, t, r, bt = b
    c = a[t:bt, l:r].copy()
    ys, xs = np.where(c[..., 3] > 0)
    return c[ys.min():ys.max() + 1, xs.min():xs.max() + 1]


def compose(parts):
    """parts: [(array, x, y)] on a transparent canvas just big enough, later parts on top."""
    w = max(x + p.shape[1] for p, x, y in parts)
    h = max(y + p.shape[0] for p, x, y in parts)
    cv = np.zeros((h, w, 4), dtype=np.uint8)
    for p, x, y in parts:
        ph, pw = p.shape[:2]
        m = p[..., 3] > 0
        cv[y:y + ph, x:x + pw][m] = p[m]
    return cv


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--atlas", default=os.path.join(os.environ.get("RTS_ART_PACKS", "/tmp/claude-0/s15-packs"), "Atlas", "terrain_atlas.png"))
    ns = ap.parse_args()
    a = np.asarray(Image.open(ns.atlas).convert("RGBA")).copy()

    cube = blob(a, (432, 753)); chunk = blob(a, (462, 750)); slab = blob(a, (494, 753))
    pieces = {
        # kind: [variant 0, 1, 2]   each (array, origin_x_frac, origin_y_frac) -- origin = the point that stands on the cell centre
        "boulder": [(blob(a, (845, 817)), .5, .62), (blob(a, (889, 876)), .5, .62), (blob(a, (894, 778)), .5, .62)],
        "rubble": [(blob(a, (722, 760), 3), .5, .6),
                   (compose([(chunk, 0, 8), (cube, 24, 14), (slab, 40, 0)]), .5, .6),
                   (compose([(blob(a, (945, 780), 1), 24, 0), (box(a, (704, 798, 766, 828)), 0, 14)]), .5, .6)],
        "deadtree": [(blob(a, (753, 586)), .5, .78), (blob(a, (415, 404)), .5, .72), (blob(a, (848, 621)), .5, .82)],
        "concreteblock": [(cube, .5, .66), (chunk, .5, .66), (compose([(cube, 0, 10), (chunk, 22, 6), (slab, 46, 0)]), .5, .6)],
    }
    # shelf-pack, 1 px apart, rows no wider than 256
    placed, x, y, rowh = [], 0, 0, 0
    for kind, vs in pieces.items():
        for v, (arr, fx, fy) in enumerate(vs):
            h, w = arr.shape[:2]
            if x + w > 256: x, y, rowh = 0, y + rowh + 1, 0
            placed.append((kind, v, arr, x, y, int(round(w * fx)), int(round(h * fy))))
            x += w + 1
            rowh = max(rowh, h)
    H = y + rowh
    sheet = np.zeros((H, 256, 4), dtype=np.uint8)
    lines = ["# LPC props (S15 art-packs pilot). Generated by tools/art/fx/import_lpc_props.py -- do not hand-edit.",
             "# Source: Liberated Pixel Cup terrain_atlas.png, CC-BY-SA 3.0 / GPL-3.0 (used under GPL-3.0); artists in docs/CREDITS.md.",
             "# One [[frame]] per (kind, variant); kind = PropKind name in lower case. origin = the pixel that stands on the cell centre.",
             "", 'file = "lpc_props.png"', ""]
    for kind, v, arr, px, py, ox, oy in placed:
        h, w = arr.shape[:2]
        sheet[py:py + h, px:px + w] = arr
        lines += ["[[frame]]", f'kind = "{kind}"', f"variant = {v}", f"x = {px}", f"y = {py}", f"w = {w}", f"h = {h}", f"origin_x = {ox}", f"origin_y = {oy}", ""]
        print(f"{kind}/{v}: {w}x{h}")
    os.makedirs(OUT, exist_ok=True)
    Image.fromarray(sheet, "RGBA").save(os.path.join(OUT, "lpc_props.png"))
    with open(os.path.join(OUT, "lpc_props.props.toml"), "w", newline="\n") as fh:
        fh.write("\n".join(lines))
    print("sheet", sheet.shape[1], H)


if __name__ == "__main__":
    main()
