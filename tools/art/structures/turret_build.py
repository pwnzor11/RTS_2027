"""Build the Authority Gun Turret sheet: python3 tools/art/structures/turret_build.py [--samples 32] [--frames 0 5 ...] [--preview] [--post-only]

build_structure.py can only write 1-facing states, so this script renders and post-processes with its camera and post
functions (BS.render + structpost.run, unchanged), then rewrites the manifest with the real facing layout:
  frame of facing f, animation step k in a state = first + f * frames + k   (same indexing as vehicles; facing 0 = north,
  clockwise, 22.5 deg steps; the base is identical in every frame, only the head turns).
Sheet: 4 columns, frame_w x frame_h = 80 x 104, 70 frames (idle 16, fire 32, damaged 16, build 6).
"""
import argparse
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, os.path.dirname(HERE))
import build_structure as BS   # noqa: E402
import structpost              # noqa: E402
import common as C             # noqa: E402


def write_manifest(mod, path):
    fw, fh = mod.CANVAS
    ox, oy = mod.ORIGIN
    L = [
        f"# Sprite manifest for {mod.ID} ({mod.TITLE}). Generated by tools/art/structures/turret_build.py -- do not hand-edit.",
        "# Frames are packed row-major, 4 per row. origin_x/origin_y = pixel of the footprint's top-left cell corner inside a frame;",
        "# the footprint is 1x1 cell = 64x64 px (the frame has an 8 px margin left/right for barrel and muzzle flash).",
        "# The head ROTATES: facings index like vehicles. Frame of facing f, animation step k in a state = first + f * frames + k.",
        "# Facing 0 = north, clockwise, 22.5 deg steps; the base is identical in all facings.",
        "# idle = 16 x 1, fire = 16 x 2 (k0 muzzle flash + recoil, k1 flash dying), damaged = 16 x 1 (structural), build = 1 x 6.",
        "# [[fx]] anchors are frame pixels (D-069); the head stays centred in every facing, so one anchor set covers all facings.",
        "",
        f'file = "{mod.ID}.png"',
        f"frame_w = {fw}",
        f"frame_h = {fh}",
        f"origin_x = {ox}",
        f"origin_y = {oy}",
        "",
    ]
    first = 0
    for name, facings, frames, tpf in mod.MANIFEST_STATES:
        L += ["[[state]]", f'name = "{name}"', f"facings = {facings}", f"frames = {frames}", f"first = {first}", f"ticks_per_frame = {tpf}", ""]
        first += facings * frames
    for fx in getattr(mod, "FX", []):
        L += ["[[fx]]", f'state = "{fx["state"]}"', f'kind = "{fx["kind"]}"', f'x = {fx["x"]}', f'y = {fx["y"]}', f'phase = {fx.get("phase", 0)}', ""]
    assert first == sum(s[1] for s in mod.STATES)
    open(path, "w").write("\n".join(L))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--samples", type=int, default=32)
    ap.add_argument("--frames", type=int, nargs="*", default=None)
    ap.add_argument("--post-only", action="store_true")
    ap.add_argument("--render-only", action="store_true")
    ap.add_argument("--preview", action="store_true")
    a = ap.parse_args()
    mod = BS.load_module("auth_turret")
    wd = BS.work_dir(mod.ID)
    if not a.post_only:
        BS.render(mod.ID, mod, a.samples, set(a.frames or []), a.preview)
    if not (a.render_only or a.preview):
        structpost.run(mod.ID, mod, wd)
        write_manifest(mod, os.path.join(C.ROOT, "data", "sprites", "buildings", f"{mod.ID}.sprite.toml"))


if __name__ == "__main__":
    main()
