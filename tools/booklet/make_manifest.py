"""Regenerate tools/booklet/render_manifest.toml from data/rules/*.toml and the model scripts under tools/art/.

Usage (repo root):  python3 tools/booklet/make_manifest.py
No bpy needed.  An id is "ok" when a build module for it exists (tools/art/vehicles|infantry|structures/<id>.py, or the
tank's own script for auth_tank), "no_model" otherwise.  Re-run it when a new model script lands; the hero renderer
(render_heroes.py) reads the result.
"""
import os
import tomllib

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT = os.path.join(ROOT, "tools", "booklet", "render_manifest.toml")

# Booklet accent per faction (the colour that the house paint is rendered in).  Values are PlayerColours.cs palette entries
# (src/Game/Sprites/PlayerColours.cs, D-068): Authority keeps amber (slot 0, as in the pilot pages); the others are picked to
# contrast their own body paint: Directorate warm greys and oxide red -> blue; Left Behind ochre, rust and teal -> purple;
# Expedition navy, lagoon white and signal orange -> pink.  Change a value here and re-run; nothing else needs to know.
ACCENTS = {
    "authority": ("#E0A020", "amber", 0),
    "directorate": ("#2F76C0", "blue", 2),
    "left_behind": ("#9360C8", "purple", 4),
    "expedition": ("#E06AA8", "pink", 7),
    "neutral": ("#E6E6DE", "white", 3),
}
PREFIX = {"auth": "authority", "dir": "directorate", "lb": "left_behind", "exp": "expedition", "neu": "neutral"}

# One vehicle, one infantry, one building per faction for the -Pilot run.  Buildings are the faction's starting building.
PILOT = {"auth_tank", "auth_rifleman", "auth_conyard",
         "dir_reactor_crawler", "dir_conscript", "dir_shaft",
         "lb_rolling_fort", "lb_scavenger", "lb_mother_rig",
         "exp_command_ship", "exp_marine", "exp_landing_depot"}

KINDS = (("vehicle", "vehicles", "vehicles"), ("infantry", "infantry", "infantry"), ("building", "buildings", "structures"))


def main():
    rows = []
    for kind, rules_file, mod_dir in KINDS:
        with open(os.path.join(ROOT, "data", "rules", rules_file + ".toml"), "rb") as f:
            d = tomllib.load(f)
        for rid, v in d.items():
            if not isinstance(v, dict):
                continue
            fac = v.get("faction") or PREFIX[rid.split("_")[0]]
            if rid == "auth_tank":     # sprite alias tank_v2 (SpriteResolver.VehicleAliases): the v2 model lives in its own script
                script, module = "tools/art/build_tank.py", ""
                ok = os.path.exists(os.path.join(ROOT, script))
            else:
                script = {"vehicle": "tools/art/build_vehicle.py", "infantry": "tools/art/build_infantry.py",
                          "building": "tools/art/build_structure.py"}[kind]
                module = f"tools/art/{mod_dir}/{rid}.py"
                ok = os.path.exists(os.path.join(ROOT, module))
            rows.append((fac, kind, rid, script, module, ok))
    order = {k: i for i, k in enumerate(("authority", "directorate", "left_behind", "expedition", "neutral"))}
    korder = {"vehicle": 0, "infantry": 1, "building": 2}
    rows.sort(key=lambda r: (order[r[0]], korder[r[1]], r[2]))

    o = ["# Booklet hero render manifest (S18-BOOKLET).  GENERATED by tools/booklet/make_manifest.py from data/rules/*.toml and",
         "# the model scripts under tools/art/: do not hand-edit, re-run the generator.",
         "#",
         "# status = \"ok\"       a build module exists; render_heroes.py reuses it unchanged (same model as the game sprite).",
         "# status = \"no_model\" no model script yet (audit GAMEREND-06: the game draws a placeholder too); skipped and listed.",
         "# script = the sprite pipeline script that owns the model; module = the per-id model module it loads (empty for the tank,",
         "#          whose model is inside build_tank.py itself).  pilot = true: included in render_heroes.ps1 -Pilot.",
         "",
         "[meta]", 'camera = "orthographic, 40 degrees, sun upper-left (same as the sprites)"',
         'view = "south-west three-quarter: facing 225 degrees clockwise from north (sheet facing 10 of 16, 5 of 8)"',
         "long_side_px = 1600", 'output = "art/booklet/<faction>/<id>.png"', "",
         "# House colour (the paint that is magenta in the sprite sheets) is rendered in this colour in the booklet.",
         "# Values are PlayerColours.cs palette entries (slot = index there).", ""]
    for fac, (hx, name, slot) in ACCENTS.items():
        o += [f"[accent.{fac}]", f'color = "{hx}"', f'name = "{name}"', f"palette_slot = {slot}", ""]
    n_ok = n_no = 0
    for fac, kind, rid, script, module, ok in rows:
        o.append(f"[hero.{rid}]")
        o.append(f'faction = "{fac}"')
        o.append(f'kind = "{kind}"')
        o.append(f'script = "{script}"' if ok else 'script = ""')
        o.append(f'module = "{module}"' if ok else 'module = ""')
        o.append(f'status = "{"ok" if ok else "no_model"}"')
        if rid in PILOT:
            o.append("pilot = true")
        o.append("")
        n_ok += ok
        n_no += not ok
    with open(OUT, "w", newline="\n") as f:
        f.write("\n".join(o))
    print(f"wrote {OUT}: {n_ok} ok, {n_no} no_model, {len(rows)} ids")


if __name__ == "__main__":
    main()
