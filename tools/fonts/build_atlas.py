"""Rasterises the UI font faces in data/fonts into bitmap atlases (see tools/fonts/README.md).

For every face and size it writes:
  <face>_<size>.png        white glyphs with straight alpha (RGB 255, A = coverage), grid layout
  <face>_<size>.font.toml  line metrics, per-glyph rectangle and offsets, and kerning pairs

The output is deterministic for a given Pillow/FreeType build: no timestamps, fixed glyph order, integer metrics.
Requires Pillow built with raqm (the kerning and ligature control depend on it).
"""
from __future__ import annotations

import argparse
import math
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFont, features

# Face name used in file names -> TTF file in data/fonts. Both are Noto Sans (OFL-1.1), see docs/CREDITS.md.
FACES = (
    ("noto-sans-regular", "NotoSans-Regular.ttf"),
    ("noto-sans-bold", "NotoSans-Bold.ttf"),
)
DEFAULT_SIZES = (12, 16, 24)
GRID_COLUMNS = 16
CELL_PAD = 1
# Latin-1 printable range, minus the C1 controls (U+007F..U+009F), plus the typographic extras the UI uses.
EXTRA_CODEPOINTS = (0x2013, 0x2014, 0x2018, 0x2019, 0x201C, 0x201D, 0x2022, 0x2026)
# Turned off so each character is laid out alone, exactly as the game draws it (no ligature substitution).
FEATURES = ["-liga", "-clig", "-calt", "-dlig"]


def charset() -> list[int]:
    """Returns the codepoints in the atlas, ascending: U+0020..U+00FF without C1 controls, plus the extras."""
    latin1 = [c for c in range(0x20, 0x100) if not 0x7F <= c <= 0x9F]
    return sorted(set(latin1) | set(EXTRA_CODEPOINTS))


def build(face: str, ttf: Path, size: int, out_dir: Path) -> None:
    """Writes the atlas PNG and metrics TOML for one face at one size."""
    font = ImageFont.truetype(str(ttf), size, layout_engine=ImageFont.Layout.RAQM)
    ascent, descent = font.getmetrics()
    line_height = ascent + descent
    baseline = ascent
    codepoints = charset()

    glyphs = []
    for cp in codepoints:
        ch = chr(cp)
        advance = round(font.getlength(ch, features=FEATURES))
        left, top, right, bottom = font.getbbox(ch, anchor="ls", features=FEATURES)
        w, h = right - left, bottom - top
        if w <= 0 or h <= 0:
            glyphs.append({"cp": cp, "mask": None, "w": 0, "h": 0, "xoff": 0, "yoff": 0, "adv": advance})
            continue
        mask = Image.new("L", (w, h), 0)
        ImageDraw.Draw(mask).text((-left, -top), ch, font=font, fill=255, anchor="ls", features=FEATURES)
        glyphs.append({"cp": cp, "mask": mask, "w": w, "h": h, "xoff": left, "yoff": baseline + top, "adv": advance})

    # Grid packing in codepoint order; every cell is as large as the largest glyph so placement is trivial.
    cell_w = max(g["w"] for g in glyphs) + 2 * CELL_PAD
    cell_h = max(g["h"] for g in glyphs) + 2 * CELL_PAD
    rows = math.ceil(len(glyphs) / GRID_COLUMNS)
    tex_w, tex_h = GRID_COLUMNS * cell_w, rows * cell_h
    coverage = Image.new("L", (tex_w, tex_h), 0)
    placed = []
    for i, g in enumerate(glyphs):
        col, row = i % GRID_COLUMNS, i // GRID_COLUMNS
        x, y = col * cell_w + CELL_PAD, row * cell_h + CELL_PAD
        if g["mask"] is not None:
            coverage.paste(g["mask"], (x, y))
        placed.append((x, y))

    white = Image.new("L", (tex_w, tex_h), 255)
    atlas = Image.merge("RGBA", (white, white, white, coverage))
    name = f"{face}_{size}"
    atlas.save(out_dir / f"{name}.png", format="PNG")

    kerning = kerning_pairs(font, codepoints)
    lines = [
        "# Generated by tools/fonts/build_atlas.py. Do not edit by hand; see tools/fonts/README.md.",
        "format = 1",
        f'face = "{face}"',
        f"size = {size}",
        f'texture = "{name}.png"',
        f"texture_width = {tex_w}",
        f"texture_height = {tex_h}",
        f"line_height = {line_height}",
        f"baseline = {baseline}",
        "",
    ]
    for g, (x, y) in zip(glyphs, placed):
        lines += [
            "[[glyph]]",
            f"codepoint = {g['cp']}",
            f"x = {x if g['w'] else 0}",
            f"y = {y if g['w'] else 0}",
            f"w = {g['w']}",
            f"h = {g['h']}",
            f"xoffset = {g['xoff'] if g['w'] else 0}",
            f"yoffset = {g['yoff'] if g['w'] else 0}",
            f"advance = {g['adv']}",
            "",
        ]
    for left, right, amount in kerning:
        lines += ["[[kerning]]", f"left = {left}", f"right = {right}", f"amount = {amount}", ""]
    (out_dir / f"{name}.font.toml").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print(f"{name}: {len(glyphs)} glyphs, {len(kerning)} kerning pairs, {tex_w}x{tex_h} px, line {line_height}")


def kerning_pairs(font: ImageFont.FreeTypeFont, codepoints: list[int]) -> list[tuple[int, int, int]]:
    """Returns (left, right, amount) for every pair whose GPOS kerning rounds to a non-zero whole pixel amount."""
    single = {cp: font.getlength(chr(cp), features=FEATURES) for cp in codepoints}
    pairs = []
    for a in codepoints:
        for b in codepoints:
            pair = font.getlength(chr(a) + chr(b), features=FEATURES) - single[a] - single[b]
            amount = round(pair)
            if amount != 0:
                pairs.append((a, b, amount))
    return pairs


def main(argv: list[str]) -> int:
    """Entry point: builds every face at every requested size."""
    root = Path(__file__).resolve().parents[2]
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--sizes", type=int, nargs="+", default=list(DEFAULT_SIZES), help="pixel sizes (em)")
    parser.add_argument("--fonts-dir", type=Path, default=root / "data" / "fonts", help="folder with the TTF files")
    parser.add_argument("--out", type=Path, default=None, help="output folder (default: the fonts folder)")
    args = parser.parse_args(argv)

    if not features.check("raqm"):
        print("error: Pillow was built without raqm; kerning would be missing", file=sys.stderr)
        return 1
    out_dir = args.out or args.fonts_dir
    out_dir.mkdir(parents=True, exist_ok=True)
    for face, ttf_name in FACES:
        ttf = args.fonts_dir / ttf_name
        if not ttf.is_file():
            print(f"error: missing {ttf}", file=sys.stderr)
            return 1
        for size in args.sizes:
            build(face, ttf, size, out_dir)
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
